# as docs/e2e/csharp/ extracts them: "root" is the path given to extract.py; "prepare"
# runs in the checkout before the key (restore, and a build where code is generated by
# MSBuild tasks rather than source generators: gRPC); "loads" are what TypeUses opens,
# with MSBuild global properties after `;`
