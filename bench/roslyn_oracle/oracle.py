from extract import discover  # noqa: E402

FIXTURE = ROOT / "tests" / "fixtures" / "csharp" / "body"
SUFFIXES = (".cs",)
IMAGE = "draftsman-roslyn"
NUGET = "draftsman-nuget"
# Debug, as `dotnet build` builds by default: `#if DEBUG` is read
