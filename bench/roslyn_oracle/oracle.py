"""Roslyn as the answer key for C# body relations (issue #5).

TypeUses/ records every name Roslyn's SemanticModel resolves in a body, once per
compilation, in the format bench/answer_key.py gives; this script runs it in a container
and joins the compilations each file is in.

    uv run bench/roslyn_oracle/oracle.py selftest
    uv run bench/roslyn_oracle/oracle.py key DIR [-o OUT.jsonl] [--compare] [-v]
    uv run bench/roslyn_oracle/oracle.py run REPO --checkout DIR -o OUT.jsonl
    uv run bench/roslyn_oracle/oracle.py scope REPO OUT.jsonl ir.json
    uv run bench/roslyn_oracle/oracle.py compare REPO OUT.jsonl --checkout DIR [-v]
    uv run bench/roslyn_oracle/oracle.py measure OUT.jsonl [--ir ir.json]

`selftest` checks the key against the hand-written answers in tests/fixtures/csharp/body
(tests/fixtures/java/body/README.md gives the marker format). `key` answers for any
directory: every `.csproj` below it is compiled, every `.cs` file below it recorded, and
`--compare` checks the extractor's body relations of the same files against it. `run`
compiles a repository's projects as REPOS below gives them and records the sources its
end-to-end page extracts (docs/e2e/csharp/); the checkout is restored (and built, where
REPOS says) in the container first, which takes the network. `scope` fails unless the key
saw the same types, declared in the same files, as ir.json of those sources. `compare`
extracts the same sources and checks every name a body relation is drawn from against
what Roslyn resolved at its place. `measure` prints what the rules for hiding names are
decided by.

A file several compilations compile (target frameworks, a file linked into several
projects) has the answers of all of them: where they agree, that is the record; where
they differ, or one of them compiles the place and records nothing there, its kind is
"split": no relation may be drawn there. A place is "not compiled" only when no
compilation compiles it (an `#if` branch no compilation takes, a file no project
compiles); one compilation is enough for its answer. Only a type declared in the sources
is the project's, and a project type is told by the files declaring it as well as by its
id (two projects' `partial class Program` share an id).

Everything runs in the image the Dockerfile here describes (built as `draftsman-roslyn`,
pinned .NET SDKs 8.0, 10.0 and 11.0, Roslyn 5.12.0); NuGet's packages are kept in the
Docker volume `draftsman-nuget`. Nothing is installed on the host but Docker.
"""

from __future__ import annotations

